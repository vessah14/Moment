// Fonction de traduction de la page : identité en français ; en anglais, le texte du
// dictionnaire s'il existe, sinon le texte d'origine. t.lang et t.locale servent aux dates.
export function makeTranslator(dictionary, lang) {
  const t = lang === 'en' && dictionary ? (text) => (typeof text === 'string' && dictionary[text.trim()]) || text : (text) => text
  t.lang = lang === 'en' ? 'en' : 'fr'
  t.locale = t.lang === 'en' ? 'en-GB' : 'fr-FR'
  return t
}

export const identity = makeTranslator(null, 'fr')
