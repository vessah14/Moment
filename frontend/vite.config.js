import tailwindcss from "@tailwindcss/vite";
import react from "@vitejs/plugin-react";
import { defineConfig, loadEnv } from "vite";
import cspPlugin from "./csp.build.js";
import seoPlugin from "./seo.build.js";

// SEO (robots.txt, sitemap.xml, une page HTML par route publique) : voir seo.build.js.
// Les sites d'événements (/e/:slug) sont listés par le backend (sitemap-events.xml).

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), "");
  return {
  // The prototype frontend runs locally over plain HTTP. The browser blocks
  // the self-signed cert generated by the basic-ssl plugin before the app loads,
  // which is why Chrome shows the “not private” warning page.
  // CSP générée au build (voir csp.build.js), avant les pages pré-rendues par seoPlugin.
  plugins: [react(), tailwindcss(), cspPlugin(env), seoPlugin(env)],
  server: {
    host: "localhost",
    port: 5173,
    strictPort: true,
  },
  preview: {
    host: "localhost",
    port: 4173,
    strictPort: true,
  },
  build: {
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (!id.includes("node_modules")) return undefined;

          if (id.includes("recharts")) return "charts";
          // jsPDF et ses dépendances : laissés au découpage automatique, pour qu'ils ne soient
          // chargés qu'au téléchargement d'un billet (import dynamique dans utils/ticketPrint.js).
          if (/node_modules[\\/](jspdf|fflate|html2canvas|canvg|rgbcolor|stackblur-canvas|svg-pathdata|dompurify|core-js|raf|performance-now)[\\/]/.test(id))
            return undefined;
          if (id.includes("react-router-dom")) return "router";
          if (id.includes("lucide-react") || id.includes("country-flag-icons"))
            return "icons";
          if (id.includes("react") || id.includes("scheduler"))
            return "react-vendor";
          return "vendor";
        },
      },
    },
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.js"],
  },
  };
});
