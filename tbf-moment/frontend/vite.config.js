// Pages publiques proposées aux moteurs de recherche. Les sites d'événements (/e/:slug)
// sont listés par le backend (sitemap-events.xml), uniquement s'ils sont publiés et que
// l'organisateur a activé « Visible sur Google ».
const SITEMAP_PAGES = [
  { path: "/", priority: "1.0", changefreq: "weekly" },
  { path: "/modeles", priority: "0.9", changefreq: "weekly" },
  { path: "/tarifs", priority: "0.8", changefreq: "monthly" },
  { path: "/ecosysteme", priority: "0.6", changefreq: "monthly" },
  { path: "/support", priority: "0.5", changefreq: "monthly" },
  { path: "/inscription", priority: "0.5", changefreq: "yearly" },
  { path: "/mentions-legales", priority: "0.2", changefreq: "yearly" },
  { path: "/cgu", priority: "0.2", changefreq: "yearly" },
  { path: "/confidentialite", priority: "0.2", changefreq: "yearly" },
  { path: "/cookies", priority: "0.2", changefreq: "yearly" },
];

// Espaces privés ou personnels : jamais explorés (ils portent aussi un "noindex").
const DISALLOWED = [
  "/dashboard",
  "/builder/",
  "/invitation/",
  "/cadeaux/",
  "/connexion",
  "/bienvenue",
  "/mot-de-passe-oublie",
  "/reinitialiser-mot-de-passe",
  "/verifier-email",
  "/auth/",
  "/loading",
  "/chargement",
];

// Génère robots.txt et sitemap.xml avec la vraie adresse du site (VITE_SITE_URL), au
// lieu de fichiers statiques qui figeraient un domaine.
function seoFiles(env) {
  const site = (env.VITE_SITE_URL || "http://localhost:5173").replace(/\/+$/, "");
  const apiOrigin = (env.VITE_API_URL || "").replace(/\/api\/?$/, "");
  const sitemaps = [`${site}/sitemap.xml`];
  if (apiOrigin) sitemaps.push(`${apiOrigin}/sitemap-events.xml`);

  const robots = [
    "User-agent: *",
    "Allow: /",
    ...DISALLOWED.map((path) => `Disallow: ${path}`),
    "",
    ...sitemaps.map((url) => `Sitemap: ${url}`),
    "",
  ].join("\n");

  const today = new Date().toISOString().slice(0, 10);
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${SITEMAP_PAGES.map(
  (page) => `  <url>
    <loc>${site}${page.path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${page.changefreq}</changefreq>
    <priority>${page.priority}</priority>
  </url>`,
).join("\n")}
</urlset>
`;

  const files = { "robots.txt": robots, "sitemap.xml": sitemap };
  return {
    name: "tbf-seo-files",
    // En dev : servis à la volée.
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const name = req.url?.slice(1);
        if (!files[name]) return next();
        res.setHeader(
          "Content-Type",
          name.endsWith(".xml") ? "application/xml; charset=utf-8" : "text/plain; charset=utf-8",
        );
        res.end(files[name]);
      });
    },
    // Au build : écrits dans dist/.
    generateBundle() {
      for (const [fileName, source] of Object.entries(files)) {
        this.emitFile({ type: "asset", fileName, source });
      }
    },
  };
}

// https://vite.dev/config/
export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), "");
  return {
  // The prototype frontend runs locally over plain HTTP. The browser blocks
  // the self-signed cert generated by the basic-ssl plugin before the app loads,
  // which is why Chrome shows the “not private” warning page.
  plugins: [react(), tailwindcss(), seoFiles(env)],
  server: {
    host: "localhost",
    port: 5173,
    strictPort: true,
  },
  preview: {
    host: "localhost",
    port: 4173,
    strictPort: true,
  },
  build: {
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (!id.includes("node_modules")) return undefined;

          if (id.includes("recharts")) return "charts";
          if (id.includes("react-router-dom")) return "router";
          if (id.includes("lucide-react") || id.includes("country-flag-icons"))
            return "icons";
          if (id.includes("react") || id.includes("scheduler"))
            return "react-vendor";
          return "vendor";
        },
      },
    },
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.js"],
  },
  };
});
